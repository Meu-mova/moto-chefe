-- Avaliações do Google por loja e a plaquinha NFC/QR que leva o cliente a avaliar.
-- Tudo por grupo. Conteúdo vindo do Google (avaliações, histórico de nota) vive no máximo
-- 30 dias, como pedem os termos da Google Maps Platform: o cron apaga o que passou disso.

-- Chave da Places API do grupo, cifrada com src/lib/cripto.ts. Nunca volta para a tela.
create table avaliacoes_google_config (
  grupo_id       uuid primary key references grupos(id),
  api_key        text not null,
  atualizado_em  timestamptz not null default now(),
  atualizado_por uuid
);

-- Ficha da loja no Google (Place ID) e a última leitura.
create table avaliacoes_google_lojas (
  loja_id            uuid primary key references lojas(id),
  grupo_id           uuid not null references grupos(id),
  place_id           text,
  nota               numeric(2,1),
  total_avaliacoes   integer,
  maps_uri           text,
  sincronizado_em    timestamptz,
  erro_sincronizacao text,
  criado_em          timestamptz not null default now()
);
create index avaliacoes_google_lojas_grupo_idx on avaliacoes_google_lojas (grupo_id);

-- As avaliações que a Places API devolve (até 5 por consulta). google_id é o `name` da review.
create table avaliacoes_google (
  id           uuid primary key default gen_random_uuid(),
  grupo_id     uuid not null references grupos(id),
  loja_id      uuid not null references lojas(id),
  google_id    text not null,
  autor        text,
  autor_uri    text,
  nota         smallint not null,
  texto        text,
  publicada_em timestamptz,
  vista_em     timestamptz not null default now(),
  constraint avaliacoes_google_loja_google_key unique (loja_id, google_id)
);
create index avaliacoes_google_grupo_idx on avaliacoes_google (grupo_id, publicada_em desc);

-- Uma foto por loja por dia, para mostrar a variação da nota e do total.
create table avaliacoes_google_historico (
  loja_id          uuid not null references lojas(id),
  grupo_id         uuid not null references grupos(id),
  dia              date not null,
  nota             numeric(2,1),
  total_avaliacoes integer,
  primary key (loja_id, dia)
);

-- Cada plaquinha física: de uma loja e, opcionalmente, de um vendedor. O código vai no link
-- gravado na tag (/avaliar/<codigo>): é público e não revela id de loja nem de pessoa.
-- Desativada (vendedor saiu, tag perdida) continua levando ao Google, mas não conta toque.
create table avaliacoes_google_placas (
  id          uuid primary key default gen_random_uuid(),
  grupo_id    uuid not null references grupos(id),
  loja_id     uuid not null references lojas(id),
  usuario_id  uuid references usuarios(id),
  nome        text,
  codigo      text not null unique,
  ativa       boolean not null default true,
  criado_em   timestamptz not null default now(),
  criado_por  uuid
);
create index avaliacoes_google_placas_grupo_idx on avaliacoes_google_placas (grupo_id);

-- Cada toque na placa (NFC) ou leitura do QR. Sem IP nem dado do cliente. usuario_id é o
-- responsável pela placa NA HORA do toque: trocar o dono da placa não muda o passado.
create table avaliacoes_google_toques (
  id         bigint generated by default as identity primary key,
  grupo_id   uuid not null references grupos(id),
  loja_id    uuid not null references lojas(id),
  placa_id   uuid not null references avaliacoes_google_placas(id),
  usuario_id uuid references usuarios(id),
  origem     text not null check (origem in ('nfc', 'qr')),
  criado_em  timestamptz not null default now()
);
create index avaliacoes_google_toques_grupo_idx on avaliacoes_google_toques (grupo_id, criado_em);
